import torch
from unsloth import FastLanguageModel

max_seq_length = 2048 # 可以根據對話長度調整
dtype = None # None 讓系統自動偵測
load_in_4bit = True # 使用 4-bit 量化以節省記憶體（免費 T4 必開）

model, tokenizer = FastLanguageModel.from_pretrained(
    model_name = "unsloth/Qwen2.5-7B-Instruct", # 選擇開源基底模型
    max_seq_length = max_seq_length,
    dtype = dtype,
    load_in_4bit = load_in_4bit,
)

model = FastLanguageModel.get_peft_model(
    model,
    r = 16, # 建議值：8, 16, 32
    target_modules = ["q_proj", "k_proj", "v_proj", "o_proj",
                      "gate_proj", "up_proj", "down_proj"],
    lora_alpha = 16,
    lora_dropout = 0,
    bias = "none",
    use_gradient_checkpointing = "unsloth", # 節省 VRAM
    random_state = 3407,
)

from datasets import load_dataset

# 讀取指定的 jsonl 檔案
dataset = load_dataset('json', data_files='training/data/menmesvento_data.jsonl', split='train')

# 檢查第一筆資料是否正確讀取
print(dataset[0])

from trl import SFTTrainer
from transformers import TrainingArguments
from unsloth import is_bfloat16_supported
import torch
...
trainer = SFTTrainer(
    model = model,
    tokenizer = tokenizer,
    train_dataset = dataset,
    dataset_text_field = "text", # 對應我們 map 產生的 text 欄位
    max_seq_length = max_seq_length,
    dataset_num_proc = 2,
    args = TrainingArguments(
        per_device_train_batch_size = 1,
        gradient_accumulation_steps = 8,
        warmup_steps = 5,
        max_steps = 60,
        learning_rate = 2e-4,
        fp16 = not is_bfloat16_supported(),
        bf16 = is_bfloat16_supported(),
        logging_steps = 1,
        output_dir = "training/outputs/menmesvento_checkpoints",
    ),
)

trainer_stats = trainer.train()

from unsloth import FastLanguageModel
FastLanguageModel.for_inference(model) # 啟用推理模式

# 使用與訓練一致的對話格式
messages = [
    {"role": "system", "content": "你是流塵谷生死簿看守者門梅司文托（前木乃伊）。你避居深殿、對兩族狂熱極度麻木，並掌管著每次施展都需承受生者記憶與悲傷反噬的『塵歸令』。"},
    {"role": "user", "content": "這個裂沙者已經沒救了"}
]

inputs = tokenizer.apply_chat_template(
    messages,
    tokenize = True,
    add_generation_prompt = True, # 加入 Assistant 引導字
    return_tensors = "pt",
).to("cuda")

outputs = model.generate(input_ids = inputs, max_new_tokens = 128, use_cache = True)
print(tokenizer.decode(outputs[0], skip_special_tokens=True))

model.save_pretrained("training/outputs/menmesvento_lora_model")
tokenizer.save_pretrained("training/outputs/menmesvento_lora_model")
print("模型已儲存至 training/outputs/menmesvento_lora_model")